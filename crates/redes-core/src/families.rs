/// Tipo de dato del atributo.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AttrType {
    Num,
    Int,
    Bool,
    Text,
    Enum(&'static [&'static str]),
}

impl AttrType {
    pub fn key(self) -> &'static str {
        match self {
            AttrType::Num => "num",
            AttrType::Int => "int",
            AttrType::Bool => "bool",
            AttrType::Text => "text",
            AttrType::Enum(_) => "enum",
        }
    }
    #[cfg(test)]
    pub fn options(self) -> &'static [&'static str] {
        match self {
            AttrType::Enum(o) => o,
            _ => &[],
        }
    }
}

/// Valor de un atributo, tanto el default del esquema como el valor de una instancia.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum Value {
    Num(f64),
    Int(i64),
    Bool(bool),
    Text(String),
}

impl Value {
    pub fn as_f64(&self) -> Option<f64> {
        match self {
            Value::Num(n) => Some(*n),
            Value::Int(i) => Some(*i as f64),
            _ => None,
        }
    }
    pub fn as_str(&self) -> Option<&str> {
        match self {
            Value::Text(s) => Some(s),
            _ => None,
        }
    }
    #[cfg(test)]
    pub fn as_bool(&self) -> Option<bool> {
        match self {
            Value::Bool(b) => Some(*b),
            _ => None,
        }
    }
}

/// Restricción declarativa; la evalúa el motor de validación, no la UI.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Constraint {
    Min(f64),
    Max(f64),
    Positive,
    NonNegative,
    OneOf(&'static [&'static str]),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Group {
    General,
    Geometrico,
    Hidraulico,
    Estructural,
    Material,
    Operacion,
}

impl Group {
    pub fn key(self) -> &'static str {
        match self {
            Group::General => "general",
            Group::Geometrico => "geometrico",
            Group::Hidraulico => "hidraulico",
            Group::Estructural => "estructural",
            Group::Material => "material",
            Group::Operacion => "operacion",
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Access {
    Editable,
    ReadOnly,
    Derived,
}

impl Access {
    pub fn key(self) -> &'static str {
        match self {
            Access::Editable => "editable",
            Access::ReadOnly => "readonly",
            Access::Derived => "derived",
        }
    }
}

/// Un atributo declarado por una familia.
#[derive(Clone, Debug)]
pub struct AttrDef {
    pub key: &'static str,
    pub label: &'static str,
    pub unit: Unit,
    pub ty: AttrType,
    pub default: Option<Value>,
    pub required: bool,
    pub constraints: Vec<Constraint>,
    pub group: Group,
    pub access: Access,
}

impl AttrDef {
    pub fn num(mut self, v: f64) -> Self {
        self.default = Some(Value::Num(v));
        self
    }
    pub fn int(mut self, v: i64) -> Self {
        self.default = Some(Value::Int(v));
        self
    }
    pub fn text(mut self, v: &str) -> Self {
        self.default = Some(Value::Text(v.to_string()));
        self
    }
    pub fn bounds(mut self, lo: f64, hi: f64) -> Self {
        self.constraints = vec![Constraint::Min(lo), Constraint::Max(hi)];
        self
    }
    pub fn positive(mut self) -> Self {
        self.constraints = vec![Constraint::Positive];
        self
    }
    pub fn derived(mut self) -> Self {
        self.access = Access::Derived;
        self
    }
}

/// Constructor de atributo.
pub(crate) fn attr(
    key: &'static str,
    label: &'static str,
    unit: Unit,
    ty: AttrType,
    required: bool,
    group: Group,
) -> AttrDef {
    AttrDef {
        key,
        label,
        unit,
        ty,
        default: None,
        required,
        constraints: Vec::new(),
        group,
        access: Access::Editable,
    }
}

